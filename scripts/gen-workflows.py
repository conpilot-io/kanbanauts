#!/usr/bin/env python3
"""Generate per-engine Kanbanauts agent workflow sources under .github/workflows/."""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / ".github" / "workflows"

PHASES = {
    "plan": {
        "name": "Kanbanauts — plan",
        "description": "Plan work for a GitHub issue",
        "timeout": 30,
        "max_turns": 60,
        "tools_bash": "[gh, git, jq, grep, find, cat, head, tail, wc, ls, rg]",
        "edit": "false",
        "safe_outputs": """\
safe-outputs:
  add-comment:
    max: 1
    target: "*"
    github-token: ${{ steps.kanban.outputs.token }}
  create-issue: false
""",
        "body": """\
# Kanbanauts plan

If `KANBANAUTS_SKIP` is `1`, do nothing and exit.
Otherwise plan the issue. Follow the imported prompt.
Call `kanban_report` with status `succeeded` (map from ready), `blocked`, `no_code`, or `failed`.
""",
        "prompt": "shared/prompts/plan.md",
    },
    "doit": {
        "name": "Kanbanauts — implement and open PR",
        "description": "Implement a plan, open a draft PR",
        "timeout": 60,
        "max_turns": 80,
        "tools_bash": '["*"]',
        "edit": "true",
        "safe_outputs": """\
safe-outputs:
  add-comment:
    max: 2
    target: "*"
    github-token: ${{ steps.kanban.outputs.token }}
  create-pull-request:
    max: 1
    draft: true
    github-token: ${{ steps.kanban.outputs.token }}
  push-to-pull-request-branch:
    max: 1
    github-token: ${{ steps.kanban.outputs.token }}
  create-issue: false
""",
        "body": """\
# Kanbanauts doit

If `KANBANAUTS_SKIP` is `1`, do nothing and exit.
Otherwise implement the plan. Follow the imported prompt.
Use `create_pull_request` for a new branch + draft PR.
Call `kanban_report` with status `succeeded`, `blocked`, or `failed`.
""",
        "prompt": "shared/prompts/doit.md",
    },
    "review": {
        "name": "Kanbanauts — review PR",
        "description": "Review the draft PR for an issue (comment only)",
        "timeout": 30,
        "max_turns": 60,
        "tools_bash": "[gh, git, jq, grep, find, cat, head, tail, wc, ls, rg]",
        "edit": "false",
        "safe_outputs": """\
safe-outputs:
  add-comment:
    max: 1
    target: "*"
    github-token: ${{ steps.kanban.outputs.token }}
  create-pull-request-review-comment:
    max: 10
    target: "*"
    github-token: ${{ steps.kanban.outputs.token }}
  submit-pull-request-review:
    max: 1
    allowed-events: [COMMENT]
    target: "*"
    github-token: ${{ steps.kanban.outputs.token }}
  create-issue: false
""",
        "body": """\
# Kanbanauts review

If `KANBANAUTS_SKIP` is `1`, do nothing and exit.
Otherwise review the draft PR. Follow the imported prompt.
Use `create_pull_request_review_comment` and `submit_pull_request_review`
(event COMMENT only — never APPROVE or REQUEST_CHANGES).
Call `kanban_report` with status `succeeded`, `blocked`, or `failed`.
""",
        "prompt": "shared/prompts/review.md",
    },
}

ENGINES = ("claude", "codex", "gemini")

HEADER = """\
---
# Generated by scripts/gen-workflows.py — do not edit by hand.
name: {name} ({engine})
description: {description} ({engine})
on:
  workflow_call:
    inputs:
      issue_number:
        description: "Issue number"
        required: true
        type: number
      source:
        description: "How the run was started (board or command)"
        required: false
        type: string
        default: board
    secrets:
      KANBANAUTS_AI_API_KEY:
        required: false
  # The Kanbanauts GitHub App dispatches the caller. gh-aw's membership check
  # sees that bot with repository permission "none" and would skip the run.
  bots: ["kanbanauts[bot]"]

permissions:
  contents: read
  issues: read
  pull-requests: read
  actions: read
  id-token: write

timeout-minutes: {timeout}
max-turns: {max_turns}

imports:
  - shared/engine-{engine}.md
  - shared/kanban-token.md
  - shared/kanban-report.md
  - shared/kanban-preflight.md
  - shared/kanban-setup-check.md
  - {prompt}

tools:
  github:
    mode: gh-proxy
    toolsets: [default]
  bash: {tools_bash}
  edit: {edit}

env:
  GH_AW_KANBAN_PHASE: {phase}

run-name: agent {phase} #${{{{ inputs.issue_number }}}}

{safe_outputs}
# Bundle imports into the lock file so cross-repo workflow_call does not
# need a checkout of the callee's .github folder on the caller runner.
inlined-imports: true
strict: true
---

{body}
"""


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for phase, meta in PHASES.items():
        for engine in ENGINES:
            path = OUT / f"agent-{phase}-{engine}.md"
            safe_outputs = str(meta["safe_outputs"]).rstrip()
            body = str(meta["body"]).rstrip()
            # Codex ignores command allow-lists; use full bash for that engine.
            tools_bash = (
                '["*"]' if engine == "codex" else str(meta["tools_bash"])
            )
            text = HEADER.format(
                name=meta["name"],
                description=meta["description"],
                engine=engine,
                timeout=meta["timeout"],
                max_turns=meta["max_turns"],
                tools_bash=tools_bash,
                edit=meta["edit"],
                prompt=meta["prompt"],
                phase=phase,
                safe_outputs=safe_outputs,
                body=body,
            )
            path.write_text(text)
            written.append(path)
    print(f"Wrote {len(written)} workflows:")
    for path in written:
        print(f"  {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
