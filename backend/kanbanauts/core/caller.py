def render_caller_workflow(*, version: int = CALLER_VERSION) -> str:
    """Render the static customer caller workflow (stable across customers)."""
    jobs: list[str] = []
    for phase in PHASES:
        for engine in ENGINES:
            job_id = f"{phase}_{engine}"
            lock = f"agent-{phase}-{engine}.lock.yml"
            if engine == "claude":
                engine_if = (
                    "(vars.KANBANAUTS_ENGINE || 'claude') == 'claude'"
                )
            else:
                engine_if = f"vars.KANBANAUTS_ENGINE == '{engine}'"
            jobs.append(
                dedent(
                    f"""\
                    {job_id}:
                      if: >-
                        inputs.phase == '{phase}' && {engine_if}
                      uses: {CENTRAL_REPO}/.github/workflows/{lock}@{CENTRAL_REF}
                      with:
                        issue_number: ${{{{ inputs.issue_number }}}}
                      secrets:
                        KANBANAUTS_AI_API_KEY: ${{{{ secrets.KANBANAUTS_AI_API_KEY }}}}
                    """
                ).rstrip()
            )
    jobs_block = "\n\n".join(jobs)
    return (
        dedent(
            f"""\
            # kanbanauts-caller: {version}
            # Managed by the Kanbanauts GitHub App. Do not edit by hand unless
            # you know you need a newer caller version. Agent logic lives in
            # {CENTRAL_REPO} @{CENTRAL_REF} and updates when that tag moves.
            name: Kanbanauts
            run-name: agent ${{{{ inputs.phase }}}} #${{{{ inputs.issue_number }}}}
            on:
              workflow_dispatch:
                inputs:
                  issue_number:
                    description: Issue number
                    required: true
                    type: string
                  phase:
                    description: Phase name (plan or doit)
                    required: true
                    type: string
            concurrency:
              group: kanbanauts-${{{{ inputs.issue_number }}}}
              cancel-in-progress: false
            permissions:
              contents: read
              issues: read
              pull-requests: read
              actions: read
              id-token: write

            jobs:
            """
        )
        + _indent(jobs_block, 2)
        + "\n"
    )


def _indent(text: str, spaces: int) -> str:
    prefix = " " * spaces
    return "\n".join(prefix + line if line else line for line in text.splitlines())


def render_config(
    *,
    project_url: str | None = None,
    project_candidates: list[str] | None = None,
) -> str:
    """Render `.github/kanbanauts.yml` for a customer repo."""
    if project_url:
        project_line = project_url
        note = ""
    elif project_candidates:
        project_line = "https://github.com/orgs/YOUR_ORG/projects/1"
        listed = "\n".join(f"#   - {u}" for u in project_candidates)
        note = (
            "# Several org Projects were found. Set `project` to one of:\n"
            f"{listed}\n"
        )
    else:
        project_line = "https://github.com/orgs/YOUR_ORG/projects/1"
        note = (
            "# No org Project found automatically. Create a Project and set `project`.\n"
        )
    return (
        note
        + dedent(
            f"""\
            # Generated by the Kanbanauts GitHub App. Phases default to kanbanauts.yml.
            version: 1
            project: {project_line}
            status_field: Status
            command_prefix: /agent
            mode: opt_out
            skip_label: agent:skip
            columns:
              Plan:
                on_enter: [{{ run: plan }}]
                on_leave: [{{ cancel: true }}]
                on_no_code: {{ move_to: Done }}
              DoIt:
                on_enter: [{{ run: doit }}]
                on_leave: [{{ cancel: true }}]
                on_success: {{ move_to: Review }}
              Review:
                on_pr_approved: {{ move_to: Tests }}
              Tests:
                on_enter: []
              Done: {{}}
            """
        )
    )


def parse_caller_version(workflow_text: str) -> int | None:
    """Return the kanbanauts-caller version header, or None if missing."""
    for line in workflow_text.splitlines()[:10]:
        stripped = line.strip()
        if stripped.startswith("# kanbanauts-caller:"):
            raw = stripped.split(":", 1)[1].strip()
            try:
                return int(raw)
            except ValueError:
                return None
    return None


def setup_pr_body(
    *,
    project_url: str | None,
    project_candidates: list[str],
) -> str:
    project_step = (
        f"- [ ] Confirm Project URL in `.github/kanbanauts.yml` (`{project_url}`)"
        if project_url
        else "- [ ] Set `project` in `.github/kanbanauts.yml` to your org Project URL"
    )
    if project_candidates and not project_url:
        project_step += "\n  Candidates:\n" + "\n".join(
            f"  - `{u}`" for u in project_candidates
        )
    return dedent(
        f"""\
        ## Set up Kanbanauts

        This pull request adds the Kanbanauts caller workflow and config.

        ### Checklist
        {project_step}
        - [ ] Org **Settings → Secrets and variables → Actions**:
              add secret `KANBANAUTS_AI_API_KEY`
        - [ ] Add variable `KANBANAUTS_AI_MODEL`
              (optional: `KANBANAUTS_ENGINE`, `KANBANAUTS_AI_BASE_URL`)
        - [ ] Ensure Project columns match the config:
              Plan, DoIt, Review, Tests, Done
        - [ ] Merge this PR

        ### Notes
        - Tickets with label `agent:skip` are ignored.
        - Agent logic runs from `{CENTRAL_REPO}@{CENTRAL_REF}` and updates when that tag moves.
        - Put `agent:skip` on a ticket that needs no code change if you prefer to skip agents.
        """
    )
